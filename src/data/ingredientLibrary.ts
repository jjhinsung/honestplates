/**
 * Plain-language ingredient library for the Ingredients tab.
 *
 * Every card answers four questions in one short sentence each:
 *   what  – what it is
 *   why   – why it's in your food
 *   from  – where it comes from
 *   status + statusNote – how much to care, and who said so
 *
 * Rules for editing (enforced by __tests__/ingredientLibrary.test.ts):
 *   - Each text field is at most 20 words.
 *   - Every card links to an official source (FDA, eCFR, NIH, USDA, HHS, WHO).
 *   - "restricted" is only used when a regulator has actually banned or
 *     revoked it somewhere. Never call something dangerous without backing.
 *   - Aliases are matched as whole words, case-insensitive, punctuation ignored.
 *     "FD&C Red No. 40" is matched as "fd c red no 40", so "red no 40" works.
 *
 * Status facts were checked against FDA/HHS announcements as of Nov 2026.
 */

export type IngredientStatus = 'fine' | 'note' | 'limit' | 'restricted';

export type IngredientCategory =
  | 'vitamin'
  | 'mineral'
  | 'preservative'
  | 'color'
  | 'grain'
  | 'fat'
  | 'sweetener'
  | 'dairy'
  | 'texture'
  | 'flavor'
  | 'leavening'
  | 'other';

export type IngredientOrigin = 'plant' | 'animal' | 'mineral' | 'fermented' | 'lab' | 'mixed';

export interface IngredientCard {
  id: string;
  /** Name as people usually see it on labels. */
  name: string;
  /** Plain-English translation shown under the label name, e.g. "Vitamin B1". */
  plain?: string;
  /** Lowercase spellings to match anywhere in a label item (the name is matched too). */
  aliases: string[];
  /** Spellings that only count when they are the WHOLE item (e.g. "flour" but not "rice flour"). */
  exact?: string[];
  /** E-numbers, used to match Open Food Facts `additives_tags` (e.g. "e320"). */
  eNumbers?: string[];
  category: IngredientCategory;
  origin: IngredientOrigin;
  what: string;
  why: string;
  from: string;
  status: IngredientStatus;
  statusNote: string;
  source: { label: string; url: string };
}

